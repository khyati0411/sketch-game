import { describe, it, expect } from 'vitest';
import { renderBacklog } from '../src/backlog';
import type { Item } from '../src/schema';
import { validItems } from './fixtures';

const extra: Item[] = [
  { id: 'US-003', type: 'story', title: 'Pick word', parent: 'EP-001', release: 'R1', sprint: 'SPRINT-01', status: 'In Progress', points: 5 },
  { id: 'US-004', type: 'story', title: 'Matchmaking', parent: 'EP-001', release: 'R2', status: 'Ready', points: 8 },
];

describe('renderBacklog', () => {
  const md = renderBacklog([...validItems(), ...extra]);

  it('marks itself as generated', () => {
    expect(md).toContain('Generated by sdlc:backlog. Do not edit.');
  });

  it('groups by release, then sprint, then unscheduled', () => {
    const order = ['## R1', '### SPRINT-01: Play a round', '### Unscheduled', '## R2', '## R3'].map((h) => md.indexOf(h));
    expect(order.every((pos) => pos >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  it('orders rows by status then id and links stories', () => {
    const sprint = md.slice(md.indexOf('### SPRINT-01'), md.indexOf('### Unscheduled'));
    expect(sprint.indexOf('US-003')).toBeLessThan(sprint.indexOf('US-001')); // In Progress before Done
    expect(sprint).toContain('| [US-001](stories/US-001.md) | Create room | EP-001 | Done | 3 |');
  });

  it('totals points per section', () => {
    const sprint = md.slice(md.indexOf('### SPRINT-01'), md.indexOf('### Unscheduled'));
    expect(sprint).toContain('Total: 8 pts (3 done)');
  });

  it('shows an empty release', () => {
    expect(md.slice(md.indexOf('## R3'))).toContain('_No stories._');
  });
});
