import { RELEASES, STORY_STATUSES, type Item, type Sprint, type Story } from './schema';

const byStatusThenId = (a: Story, b: Story) =>
  STORY_STATUSES.indexOf(a.status) - STORY_STATUSES.indexOf(b.status) || a.id.localeCompare(b.id);

function storyTable(stories: Story[], linkBase: string): string {
  const rows = [...stories]
    .sort(byStatusThenId)
    .map((s) => `| [${s.id}](${linkBase}stories/${s.id}.md) | ${s.title} | ${s.parent} | ${s.status} | ${s.points ?? ''} |`);
  const pts = (list: Story[]) => list.reduce((sum, s) => sum + (s.points ?? 0), 0);
  const done = pts(stories.filter((s) => s.status === 'Done'));
  return ['| ID | Title | Epic | Status | Points |', '|---|---|---|---|---|', ...rows, '', `Total: ${pts(stories)} pts (${done} done)`].join('\n');
}

/** `linkBase` is prepended to `stories/US-###.md`: '' for docs/sdlc/backlog.md, the repo's docs/sdlc URL for the Pages site. */
export function renderBacklog(items: Item[], { linkBase = '' }: { linkBase?: string } = {}): string {
  const stories = items.filter((i): i is Story => i.type === 'story');
  const sprints = items.filter((i): i is Sprint => i.type === 'sprint').sort((a, b) => a.id.localeCompare(b.id));
  const out = ['# Backlog', '', '> Generated by sdlc:backlog. Do not edit.', ''];

  for (const release of RELEASES) {
    out.push(`## ${release}`, '');
    const inRelease = stories.filter((s) => s.release === release);
    if (inRelease.length === 0) {
      out.push('_No stories._', '');
      continue;
    }
    for (const sprint of sprints.filter((s) => s.release === release)) {
      const committed = inRelease.filter((s) => s.sprint === sprint.id);
      out.push(`### ${sprint.id}: ${sprint.goal}`, '', committed.length ? storyTable(committed, linkBase) : '_No stories._', '');
    }
    const unscheduled = inRelease.filter((s) => !s.sprint);
    if (unscheduled.length) out.push('### Unscheduled', '', storyTable(unscheduled, linkBase), '');
  }
  return out.join('\n');
}
